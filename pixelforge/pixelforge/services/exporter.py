"""ZIP export with safe filenames and a README containing run instructions."""

from __future__ import annotations

import io
import re
import zipfile

from pixelforge import __version__
from pixelforge.schemas import Project
from pixelforge.services.code_validator import validate_files, validate_path
from pixelforge.utils.errors import CodeValidationError, ExportError

README_NAME = "README.md"
_FIXED_DATE = (2020, 1, 1, 0, 0, 0)  # reproducible archives


def slugify(title: str, default: str = "pixelforge-project") -> str:
    """Filesystem-safe project folder name."""
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:40].strip("-")
    return slug or default


def build_readme(project: Project, folder: str) -> str:
    """README with exact local run instructions for the static project."""
    files = "\n".join(f"- `{path}`" for path in sorted(project.files))
    notes = f"\n## Notes from the generator\n\n{project.notes[:2000]}\n" if project.notes else ""
    return f"""# {project.title.replace(chr(10), ' ')[:100]}

Generated by PixelForge v{__version__} from a screenshot. This is an **approximation**
of the original design, not a pixel-perfect copy. **Review and test the code before deploying it.**

## Files

{files}

## Run it locally

No build step or dependencies are required.

**Option A: open directly.** Double-click `index.html`, or open it from your browser's File menu.

**Option B: serve over HTTP** (recommended; requires Python 3):

```bash
cd {folder}
python -m http.server 8000
```

Then open <http://localhost:8000>. On Windows use `py -m http.server 8000` if `python` is not on PATH.
{notes}"""


def build_zip(project: Project, folder: str | None = None) -> bytes:
    """Create a ZIP (in memory) with all project files plus a README."""
    folder = slugify(folder or project.title)
    try:
        validate_files(project.files)
        if not project.files:
            raise ExportError("There are no files to export.")
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
            for path, content in sorted(project.files.items()):
                safe = validate_path(path)
                _write(archive, f"{folder}/{safe}", content)
            _write(archive, f"{folder}/{README_NAME}", build_readme(project, folder))
        return buffer.getvalue()
    except CodeValidationError as exc:
        raise ExportError(f"Export blocked: {exc.message}") from exc


def _write(archive: zipfile.ZipFile, name: str, content: str) -> None:
    info = zipfile.ZipInfo(name, date_time=_FIXED_DATE)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o644 << 16
    archive.writestr(info, content.encode("utf-8"))
